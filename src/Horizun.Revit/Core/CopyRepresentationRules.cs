    {
        public string Kind;
        public double Base, Top, Thickness;
        public double[] Facing;
        public double[][][] Curves;
    }

    public static class CopyRepresentationRules
    {
        public const double SolidToleranceFeet = 1e-6;
        public const double LayoutToleranceFeet = 0.1 / 304.8;
        public const double RelativeVolumeTolerance = 1e-8;
        private const int ExactSampleDeltaLimit = 256;
        private const int RelationshipSearchSourceLimit = 64;
        private const int RelationshipSearchCandidateLimit = 4096;

        public static CopySignature Translate(CopySignature source, double x, double y, double z)
        {
            Func<double[], double[]> shift = p => p == null ? null : new[] { p[0] + x, p[1] + y, p[2] + z };
            return new CopySignature { Id = source.Id, IsType = source.IsType, Category = source.Category, Type = source.Type,
                Position = shift(source.Position), BoundsMin = shift(source.BoundsMin), BoundsMax = shift(source.BoundsMax),
                GeometryPoints = source.GeometryPoints?.Select(shift).ToArray(), LayoutReadError = source.LayoutReadError,
                SolidReadError = source.SolidReadError,
                IntrinsicReadError = source.IntrinsicReadError, Layers = source.Layers,
                RequiresHostEvidence = source.RequiresHostEvidence, LayerReadError = source.LayerReadError,
                RelationshipRole = source.RelationshipRole,
                CutProfile = source.CutProfile?.Select(shift).ToArray(),
                Intrinsic = source.Intrinsic == null ? null : new CopyIntrinsicEvidence
                {
                    Volume = source.Intrinsic.Volume, Samples = source.Intrinsic.Samples?.Select(shift).ToArray(),
                    BoundsMin = shift(source.Intrinsic.BoundsMin), BoundsMax = shift(source.Intrinsic.BoundsMax),
                    ExpectedVolumeWithCuts = source.Intrinsic.ExpectedVolumeWithCuts,
                    ActualVolume = source.Intrinsic.ActualVolume, IntersectionVolume = source.Intrinsic.IntersectionVolume
                },
                Solid = source.Solid == null ? null : new CopySolidEvidence
                {
                    Volume = source.Solid.Volume, ExternalCutCount = source.Solid.ExternalCutCount,
                    JoinBounds = source.Solid.JoinBounds?.Select(box => box.Select(shift).ToArray()).ToArray(),
                    OpeningLoops = source.Solid.OpeningLoops?.Select(loop => loop.Select(shift).ToArray()).ToArray(),
                    Join = source.Solid.Join, JoinReadError = source.Solid.JoinReadError,
                    Cutters = source.Solid.Cutters?.Select(s => Translate(s, x, y, z)).ToArray(),
                    Joined = source.Solid.Joined?.Select(s => Translate(s, x, y, z)).ToArray(),
                    RequestedRelationshipIds = source.Solid.RequestedRelationshipIds,
                    RelationshipReadError = source.Solid.RelationshipReadError
                },
                Layout = source.Layout == null ? null : new CopyLayout
                {
                    Kind = source.Layout.Kind, Base = source.Layout.Base + z, Top = source.Layout.Top + z,
                    Thickness = source.Layout.Thickness, Facing = source.Layout.Facing,
                    Curves = source.Layout.Curves?.Select(curve => curve?.Select(shift).ToArray()).ToArray()
                } };
        }

        /// <summary>One arrived element cannot stand in for two requested instances.</summary>
        public static List<long> Missing(IEnumerable<CopySignature> requested, IEnumerable<CopySignature> arrived,
            IEnumerable<CopySignature> reusableTypes)
        {
            var requestedList = (requested ?? Enumerable.Empty<CopySignature>()).ToList();
            var map = Map(requestedList, arrived, reusableTypes);
            return requestedList.Where(s => !map.ContainsKey(s.Id)).Select(s => s.Id).ToList();
        }

        /// <summary>One-to-one source to API-returned copy IDs; never relies on return ordering.</summary>
        public static Dictionary<long, long> Map(IEnumerable<CopySignature> requested, IEnumerable<CopySignature> arrived,
            IEnumerable<CopySignature> reusableTypes) =>
            Map(requested, arrived, reusableTypes, out _);

        internal static Dictionary<long, long> Map(IEnumerable<CopySignature> requested, IEnumerable<CopySignature> arrived,
            IEnumerable<CopySignature> reusableTypes, out Dictionary<long, JObject> relationshipFailures,
            IReadOnlyDictionary<long, long> copiesBeforeCommit = null)
        {
            var sources = (requested ?? Enumerable.Empty<CopySignature>()).GroupBy(s => s.Id)
                .Select(g => g.First()).OrderBy(s => s.Id).ToArray();
            var candidates = (arrived ?? Enumerable.Empty<CopySignature>()).GroupBy(c => c.Id)
                .Select(g => g.First()).OrderBy(c => c.Id).ToArray();
            var reused = (reusableTypes ?? Enumerable.Empty<CopySignature>()).Where(c => c.IsType).OrderBy(c => c.Id).ToArray();
            bool SameCopy(CopySignature source, CopySignature candidate) => copiesBeforeCommit == null ||
                copiesBeforeCommit.TryGetValue(source.Id, out long id) && id == candidate.Id;
            var edges = sources.Select(s => candidates.Where(c => SameCopy(s, c) && MatchBasis(s, c) != null)
                .Select(c => c.Id).ToArray()).ToArray();
            var owner = new Dictionary<long, int>();
            for (int source = 0; source < sources.Length; source++)
                Assign(source, edges, owner, new HashSet<long>());

            var map = owner.ToDictionary(pair => sources[pair.Value].Id, pair => pair.Key);
            foreach (CopySignature source in sources.Where(s => s.IsType && !map.ContainsKey(s.Id)))
            {
                CopySignature match = reused.FirstOrDefault(c => SameCopy(source, c) && SameIdentity(source, c));
                if (match != null) map.Add(source.Id, match.Id);
            }
            relationshipFailures = new Dictionary<long, JObject>();
            var byId = candidates.ToDictionary(c => c.Id);
            var relatedSources = sources.Where(s => s.Solid?.RequestedRelationshipIds?.Count > 0).ToArray();
            foreach (CopySignature source in relatedSources)
            {
                if (map.TryGetValue(source.Id, out long copyId) &&
                    byId.TryGetValue(copyId, out CopySignature copy))
                {
                    JObject failure = RequestedRelationshipFailure(source.Solid, copy.Solid, map);
                    if (failure != null)
                    {
                        failure["copy_id"] = copyId;
                        relationshipFailures.Add(source.Id, failure);
                    }
                }
            }
            // The committed reread must prove the same IDs that passed before commit.
            if (relationshipFailures.Count > 0 && map.Count == sources.Length && copiesBeforeCommit == null)
            {
                var alternative = FindRelationshipMapping(sources, edges, map, relatedSources, byId,
                    out string limit, out long untriedBranches);
                if (alternative != null)
                {
                    map = alternative;
                    relationshipFailures.Clear();
                }
                else if (limit != null)
                {
                    foreach (JObject failure in relationshipFailures.Values)
                    {
                        failure["search_limit"] = limit;
                        failure["untried_branches"] = untriedBranches;
                    }
                }
            }
            foreach (long failedId in relationshipFailures.Keys)
                map.Remove(failedId);
            return sources.Where(s => map.ContainsKey(s.Id)).ToDictionary(s => s.Id, s => map[s.Id]);
        }

        private static Dictionary<long, long> FindRelationshipMapping(CopySignature[] sources, long[][] edges,
            Dictionary<long, long> original, CopySignature[] relatedSources, Dictionary<long, CopySignature> byId,
            out string limit, out long untriedBranches)
        {
            limit = null;
            untriedBranches = 0;
            var relatedIds = new HashSet<long>(relatedSources.Select(s => s.Id));
            foreach (CopySignature source in relatedSources)
                relatedIds.UnionWith(source.Solid.RequestedRelationshipIds);

            // Only instances participate in cuts and joins. Keep the original type matches and reuse decisions.
            var ambiguous = Enumerable.Range(0, sources.Length).Where(i => !sources[i].IsType && edges[i].Length > 1)
                .OrderBy(i => edges[i].Length).ThenBy(i => sources[i].Id).ToArray();
            var related = ambiguous.Where(i => relatedIds.Contains(sources[i].Id)).ToArray();
            if (related.Length == 0) return null;
            var unrelated = ambiguous.Where(i => !relatedIds.Contains(sources[i].Id)).ToArray();

            var trial = new Dictionary<long, long>(original);
            foreach (int index in ambiguous)
                trial.Remove(sources[index].Id);
            var used = new HashSet<long>(trial.Values);
            if (related.Length > RelationshipSearchSourceLimit)
            {
                limit = $"{RelationshipSearchSourceLimit} ambiguous source instances";
                untriedBranches = edges[related[0]].Count(candidate => !used.Contains(candidate));
                return null;
            }

            // Count the unvisited alternatives at the search frontier, without expanding their subtrees.
            int remaining = RelationshipSearchCandidateLimit;
            long pending = 0;
            bool Search(int depth)
            {
                if (depth == related.Length)
                {
                    if (relatedSources.Any(source => byId.TryGetValue(trial[source.Id], out CopySignature copy) &&
                        RequestedRelationshipFailure(source.Solid, copy.Solid, trial) != null))
                        return false;

                    // Unrelated copies can share candidates with related sources. Match what is left
                    // by geometry so the original choice for an unrelated source cannot block a valid map.
                    var availableEdges = unrelated.Select(i => edges[i].Where(id => !used.Contains(id)).ToArray()).ToArray();
                    var geometryOwner = new Dictionary<long, int>();
                    for (int i = 0; i < unrelated.Length; i++)
                        if (!Assign(i, availableEdges, geometryOwner, new HashSet<long>())) return false;
                    foreach (var match in geometryOwner)
                        trial.Add(sources[unrelated[match.Value]].Id, match.Key);
                    return true;
                }

                int index = related[depth];
                long sourceId = sources[index].Id;
                foreach (long candidate in edges[index])
                {
                    if (used.Contains(candidate)) continue;
                    if (remaining == 0)
                    {
                        pending++;
                        continue;
                    }
                    remaining--;
                    used.Add(candidate);
                    trial.Add(sourceId, candidate);
                    if (Search(depth + 1)) return true;
                    trial.Remove(sourceId);
                    used.Remove(candidate);
                }
                return false;
            }

            if (Search(0)) return trial;
            if (pending > 0)
            {
                limit = $"{RelationshipSearchCandidateLimit} candidate visits";
                untriedBranches = pending;
            }
            return null;
        }

        // A geometrically equivalent participant only qualifies if its ID and role match the proposed map.
        private static JObject RequestedRelationshipFailure(CopySolidEvidence source, CopySolidEvidence copy,
            IReadOnlyDictionary<long, long> map)
        {
            JObject Check(CopySignature[] sourceParticipants, CopySignature[] copyParticipants, string kind)
            {
                foreach (CopySignature participant in sourceParticipants.Where(p => source.RequestedRelationshipIds.Contains(p.Id)))
                {
                    bool mapped = map.TryGetValue(participant.Id, out long expectedId);
                    if (mapped && copyParticipants.Any(p => p.Id == expectedId && p.RelationshipRole == participant.RelationshipRole))
                        continue;
                    return new JObject
                    {
                        ["relationship_kind"] = kind,
                        ["relationship_role"] = participant.RelationshipRole,
                        ["source_participant_id"] = participant.Id,
                        ["expected_copy_participant_id"] = mapped ? new JValue(expectedId) : JValue.CreateNull(),
                        ["observed_participant_ids"] = new JArray(copyParticipants.Select(p => p.Id))
                    };
                }
                return null;
            }
            return Check(source.Cutters, copy.Cutters, "cut") ?? Check(source.Joined, copy.Joined, "join");
        }

        // A compatible candidate may already belong to a source that has an alternative.
        private static bool Assign(int source, long[][] edges, Dictionary<long, int> owner, HashSet<long> seen)
        {
            foreach (long candidate in edges[source])
            {
                if (!owner.ContainsKey(candidate))
                {
                    owner[candidate] = source;
                    return true;
                }
            }
            foreach (long candidate in edges[source])
            {
                if (seen.Add(candidate) && Assign(owner[candidate], edges, owner, seen))
                {
                    owner[candidate] = source;
                    return true;
                }
            }
            return false;
        }

        public static bool SameIdentity(CopySignature a, CopySignature b) => a != null && b != null &&
            !string.IsNullOrEmpty(a.Category) && !string.IsNullOrEmpty(a.Type) && a.IsType == b.IsType &&
            string.Equals(a.Category, b.Category, StringComparison.Ordinal) && string.Equals(a.Type, b.Type, StringComparison.Ordinal);

        public static string MatchBasis(CopySignature a, CopySignature b)
        {
            if (!SameIdentity(a, b)) return null;
            if (a.IsType) return "qualified_type";
            if (!SameLayers(a, b)) return null;
            if (a.Layout != null && b.Layout != null)
                return LayoutDelta(a.Layout, b.Layout) <= LayoutToleranceFeet && LayoutSolidCheck(a, b) != null
                    ? a.Layout.Kind : null;
            return PlacementMatches(a, b) &&
                (!(NeedsSolidEvidence(a) || NeedsSolidEvidence(b)) ||
                    RelationshipMismatch(a, b) == null && SolidMismatch(a, b) == null) &&
                SameGeometry(a.GeometryPoints, b.GeometryPoints) ? "solid_geometry" : null;
        }

        public static bool PlacementMatches(CopySignature a, CopySignature b) =>
            a.IsType || (a.Layout != null && b.Layout != null
                ? LayoutDelta(a.Layout, b.Layout) <= LayoutToleranceFeet
                : SamePosition(a.Position, b.Position) &&
                    (a.BoundsMin == null && a.BoundsMax == null ||
                    SamePosition(a.BoundsMin, b.BoundsMin) && SamePosition(a.BoundsMax, b.BoundsMax)));

        private static bool NeedsSolidEvidence(CopySignature signature) =>
            signature.RequiresHostEvidence || signature.Layout != null || signature.Solid != null || signature.SolidReadError != null;

        public static string LayoutSolidCheck(CopySignature a, CopySignature b)
        {
            if (!SameLayers(a, b) || RelationshipMismatch(a, b) != null) return null;
            if (OmittedRelationships(a, b, out long[] cuts, out _))
            {
                if (IntrinsicMismatch(a, b) == null) return "intrinsic_solid_with_omitted_relationships";
                if (cuts.Length > 0 || a.Intrinsic != null && b.Intrinsic != null) return null;
            }
            string mismatch = SolidMismatch(a, b);
            if (mismatch == null) return "volume_and_samples";
            if (mismatch != "solid_volume_differs" && mismatch != "solid_samples_differ") return null;
            CopySolidEvidence source = a.Solid, copy = b.Solid;
            if (HasRetainedRelationships(copy)) return null;
            if (a.Layout == null || b.Layout == null || source.ExternalCutCount != 0 ||
                !JoinAccountsForMaterial(source) || !JoinAccountsForMaterial(copy) ||
                source.Join.CuttingJoinCount == 0 && copy.Join.CuttingJoinCount == 0 &&
                source.Join.MiterJoinCount == 0 && copy.Join.MiterJoinCount == 0)
                return null;
            double tolerance = VolumeTolerance(source.Join.AuthoredVolume, copy.Join.AuthoredVolume);
            return Math.Abs(source.Join.AuthoredVolume - copy.Join.AuthoredVolume) <= tolerance
                ? "measured_join_difference" : null;
        }

        // A copied wall whose joins changed (a joined partner was not copied, or the destination has walls that the
        // copy joined) gets other end faces and another box in plan, so the exact translated box cannot find it. Its
        // authored wall does not change: the same qualified type and build-up, the same axis, base and top translated,
        // and a body that still spans that height. Every one is required; a copy that is really missing has no
        // candidate with that axis, so it is still reported missing.
        public static string JoinChangedWallBasis(CopySignature expected, CopySignature copy)
        {
            if (expected?.Layout == null || copy?.Layout == null || expected.IsType || copy.IsType ||
                expected.Layout.Kind != "wall_axis" || copy.Layout.Kind != "wall_axis" ||
                !SameIdentity(expected, copy) || expected.Layers == null || copy.Layers == null || !SameLayers(expected, copy))
                return null;
            if (!(LayoutDelta(expected.Layout, copy.Layout) <= LayoutToleranceFeet)) return null;
            if (expected.BoundsMin == null || expected.BoundsMax == null || copy.BoundsMin == null || copy.BoundsMax == null ||
                !(Math.Abs(expected.BoundsMin[2] - copy.BoundsMin[2]) <= LayoutToleranceFeet) ||
                !(Math.Abs(expected.BoundsMax[2] - copy.BoundsMax[2]) <= LayoutToleranceFeet))
                return null;
            return "authored_wall_join_changed";
        }

        internal static bool SameLayers(CopySignature a, CopySignature b)
        {
            if (a.Layers == null || b.Layers == null)
                return !a.RequiresHostEvidence && !b.RequiresHostEvidence && a.Layers == null && b.Layers == null;
            return a.Layers.Length == b.Layers.Length && a.Layers.Zip(b.Layers, (left, right) =>
                left.Definition == right.Definition && Math.Abs(left.Width - right.Width) <= SolidToleranceFeet).All(match => match);
        }

        internal static bool OmittedRelationships(CopySignature a, CopySignature b,
            out long[] cuts, out long[] joins)
        {
            return ReadRelationshipDifference(a.Solid, b.Solid, out cuts, out joins) == null &&
                (cuts.Length > 0 || joins.Length > 0);
        }

        internal static string RelationshipMismatch(CopySignature a, CopySignature b)
        {
            if (!a.RequiresHostEvidence && !b.RequiresHostEvidence && a.Solid?.Cutters == null &&
                a.Solid?.Joined == null && b.Solid?.Cutters == null && b.Solid?.Joined == null) return null;
            string mismatch = ReadRelationshipDifference(a.Solid, b.Solid, out long[] cuts, out long[] joins);
            if (mismatch != null) return mismatch;
            if (cuts.Length == 0 && joins.Length == 0 || !HasRetainedRelationships(b.Solid)) return null;
            if (b.Solid.Joined.Length != 0 || b.Intrinsic?.ExpectedVolumeWithCuts == null)
                return "retained_relationship_effect_unavailable";
            foreach (CopySignature copyCut in b.Solid.Cutters)
            {
                CopySignature sourceCut = a.Solid.Cutters.Single(s => SameParticipant(s, copyCut));
                if (sourceCut.CutProfile == null || copyCut.CutProfile == null)
                    return "retained_relationship_effect_unavailable";
                if (!SameGeometry(sourceCut.CutProfile, copyCut.CutProfile, LayoutToleranceFeet))
                    return "retained_cut_profile_differs";
            }
            return null;
        }

        private static bool HasRetainedRelationships(CopySolidEvidence copy) =>
            copy?.Cutters?.Length > 0 || copy?.Joined?.Length > 0;

        private static string ReadRelationshipDifference(CopySolidEvidence source, CopySolidEvidence copy,
            out long[] cuts, out long[] joins)
        {
            cuts = joins = Array.Empty<long>();
            if (source?.Cutters == null || source.Joined == null || copy?.Cutters == null || copy.Joined == null)
                return "relationship_inventory_unavailable";
            if (!FindOmitted(source.Cutters, copy.Cutters, out cuts) || !FindOmitted(source.Joined, copy.Joined, out joins))
                return "retained_relationship_differs";
            if (source.RequestedRelationshipIds?.Overlaps(cuts.Concat(joins)) == true)
                return "requested_relationship_missing";
            return null;
        }

        private static bool FindOmitted(CopySignature[] source, CopySignature[] copy, out long[] omitted)
        {
            omitted = Array.Empty<long>();
            if (source == null || copy == null || copy.Length > source.Length) return false;
            var retained = new HashSet<long>();
            foreach (CopySignature arrived in copy)
            {
                var matches = source.Where(s => SameParticipant(s, arrived)).ToArray();
                if (matches.Length != 1 || matches[0].RelationshipRole != arrived.RelationshipRole ||
                    !retained.Add(matches[0].Id)) return false;
            }
            omitted = source.Where(s => !retained.Contains(s.Id)).Select(s => s.Id).ToArray();
            return true;
        }

        private static bool SameParticipant(CopySignature source, CopySignature copy) =>
            SameIdentity(source, copy) && Delta(source.Position, copy.Position) <= LayoutToleranceFeet &&
            Delta(source.BoundsMin, copy.BoundsMin) <= LayoutToleranceFeet &&
            Delta(source.BoundsMax, copy.BoundsMax) <= LayoutToleranceFeet;

        internal static string IntrinsicMismatch(CopySignature a, CopySignature b)
        {
            CopyIntrinsicEvidence source = a.Intrinsic, copy = b.Intrinsic;
            if (source == null || copy == null || !copy.ActualVolume.HasValue || !copy.IntersectionVolume.HasValue ||
                a.Layers == null || b.Layers == null)
                return "intrinsic_solid_unavailable";
            if (!SameLayers(a, b)) return "layers_differ";
            if (!PlacementMatches(a, b) || Delta(a.Position, b.Position) > LayoutToleranceFeet ||
                Delta(source.BoundsMin, copy.BoundsMin) > LayoutToleranceFeet ||
                Delta(source.BoundsMax, copy.BoundsMax) > LayoutToleranceFeet)
                return "intrinsic_placement_differs";
            double tolerance = VolumeTolerance(source.Volume, copy.Volume);
            double expectedFinal = copy.ExpectedVolumeWithCuts ?? copy.Volume;
            if (!(source.Volume > 0 && copy.Volume > 0 && Math.Abs(source.Volume - copy.Volume) <= tolerance &&
                expectedFinal > 0 && expectedFinal <= copy.Volume + tolerance &&
                Math.Abs(copy.ActualVolume.Value - copy.IntersectionVolume.Value) <= tolerance &&
                Math.Abs(expectedFinal - copy.IntersectionVolume.Value) <= tolerance))
                return "intrinsic_solid_volume_differs";
            return source.Samples?.Length > 0 && SameGeometry(source.Samples, copy.Samples, LayoutToleranceFeet)
                ? null : "intrinsic_solid_samples_differ";
        }

        internal static JObject OmittedRelationshipWarning(CopySignature source, CopySignature copy)
        {
            if (MatchBasis(source, copy) == null ||
                !OmittedRelationships(source, copy, out long[] cuts, out long[] joins))
                return null;
            const double CubicFeetToMetres = 0.028316846592;
            return new JObject
            {
                ["source_id"] = source.Id, ["copy_id"] = copy.Id,
                ["omitted_cut_source_ids"] = new JArray(cuts),
                ["omitted_join_source_ids"] = new JArray(joins),
                ["source_volume_m3"] = source.Solid.Volume * CubicFeetToMetres,
                ["copy_volume_m3"] = copy.Solid.Volume * CubicFeetToMetres,
                ["volume_delta_m3"] = Math.Abs(copy.Solid.Volume - source.Solid.Volume) * CubicFeetToMetres,
                ["message"] = "The listed external cuts or joins were absent from the verified copy."
            };
        }

        private static bool JoinAccountsForMaterial(CopySolidEvidence solid)
        {
            CopyJoinEvidence join = solid.Join;
            if (join == null || !(join.ExpectedVolume > 0) || !(join.IntersectionVolume > 0) ||
                !(join.AuthoredVolume > 0) || double.IsInfinity(join.AuthoredVolume) ||
                join.CuttingJoinCount < 0 || join.MiterJoinCount < 0)
                return false;
            double tolerance = VolumeTolerance(Math.Max(join.AuthoredVolume, join.ExpectedVolume), solid.Volume);
            double cut = join.AuthoredVolume - join.ExpectedVolume;
            if (!(cut >= -tolerance) || (cut > tolerance) != (join.CuttingJoinCount > 0))
                return false;
            // Measure both excess and missing material. Equal total volumes can hide a displaced cut.
            return Math.Abs(solid.Volume - join.IntersectionVolume) <= tolerance &&
                Math.Abs(join.ExpectedVolume - join.IntersectionVolume) <= tolerance;
        }

        public static double VolumeTolerance(double a, double b) => Math.Max(a, b) * RelativeVolumeTolerance;

        public static string SolidMismatch(CopySignature a, CopySignature b) => SolidMismatch(a, b, out _);

        internal static string SolidMismatch(CopySignature a, CopySignature b, out long sampleIndexVisits)
        {
            sampleIndexVisits = 0;
            CopySolidEvidence source = a.Solid, copy = b.Solid;
            if (!NeedsSolidEvidence(a) && !NeedsSolidEvidence(b)) return "solid_not_measured";
            if (!HasVolume(source) || !HasVolume(copy)) return "solid_volume_unavailable";
            if (source.ExternalCutCount != copy.ExternalCutCount) return "external_cut_count_differs";
            if (source.OpeningLoops == null || copy.OpeningLoops == null) return "opening_loops_unavailable";
            if (!SameOpeningLoops(source.OpeningLoops, copy.OpeningLoops)) return "opening_loops_differ";
            if (Math.Abs(source.Volume - copy.Volume) > VolumeTolerance(source.Volume, copy.Volume))
                return "solid_volume_differs";
            if (a.GeometryPoints == null || b.GeometryPoints == null || a.GeometryPoints.Length == 0 || b.GeometryPoints.Length == 0)
                return "solid_samples_unavailable";
            return SameGeometry(a.GeometryPoints, b.GeometryPoints, LayoutToleranceFeet, out sampleIndexVisits)
                ? null : "solid_samples_differ";
        }

        private static bool HasVolume(CopySolidEvidence evidence) =>
            evidence != null && evidence.Volume > 0 && !double.IsInfinity(evidence.Volume);

        private static bool SameOpeningLoops(double[][][] a, double[][][] b)
        {
            if (a.Length != b.Length) return false;
            return HasCompleteMatching(a.Length, (i, j) => a[i] != null && a[i].Length >= 3 &&
                SameGeometry(a[i], b[j], LayoutToleranceFeet));
        }

        private static bool HasCompleteMatching(int count, Func<int, int, bool> compatible)
        {
            var indices = Enumerable.Range(0, count).ToArray();
            if (indices.All(i => compatible(i, i))) return true;
            var edges = indices.Select(i => indices.Where(j => compatible(i, j)).Select(j => (long)j).ToArray()).ToArray();
            var owner = new Dictionary<long, int>();
            return indices.All(i => Assign(i, edges, owner, new HashSet<long>()));
        }

        public static string StampFailedReread(JObject detail, string message, string status, bool rollbackConfirmed)
        {
            int requested = detail["application"]?.Value<int?>("requested") ?? detail.Value<int?>("requested") ?? 0;
            ApplicationOutcome.StampApplied(detail, status, requested, 0, 0, requested, 0, 0);
            detail["transaction_status"] = status;
            detail["rollback_confirmed"] = rollbackConfirmed;
            detail["state"] = rollbackConfirmed ? "rolled_back" : "uncertain";
            detail["host_verified"] = false;
            detail["error_code"] = rollbackConfirmed ? ErrorCodes.TransaccionRevertida : ErrorCodes.VerificacionFallida;
            return (message ?? "Copy geometry verification was incomplete.") +
                (rollbackConfirmed ? " The copy batch was rolled back." : " Rollback was not confirmed; inspect the model.");
        }

        internal static string RollBackFailedReread(JObject detail, string message,
            Func<(string Status, bool Confirmed)> rollBack, Func<JArray> mismatches = null)
        {
            (string Status, bool Confirmed) rollback;
            try { rollback = rollBack(); }
            catch (Exception ex)
            {
                rollback = ("Error", false);
                detail["rollback_error"] = ex.Message;
            }
            if (mismatches != null) detail["representation_mismatches"] = mismatches();
            return StampFailedReread(detail, message, rollback.Status, rollback.Confirmed);
        }

        public static double LayoutDelta(CopyLayout a, CopyLayout b)
        {
            if (a == null || b == null || a.Kind != b.Kind || a.Curves == null || b.Curves == null ||
                a.Curves.Length == 0 || a.Curves.Length != b.Curves.Length)
                return double.PositiveInfinity;
            if ((a.Facing != null || b.Facing != null) && Delta(a.Facing, b.Facing) > SolidToleranceFeet)
                return double.PositiveInfinity;

            double delta = new[] { Math.Abs(a.Base - b.Base), Math.Abs(a.Top - b.Top), Math.Abs(a.Thickness - b.Thickness) }.Max();
            if (double.IsNaN(delta)) return double.PositiveInfinity;
            var distances = a.Curves.Select(curve => b.Curves.Select(other => CurveDelta(curve, other)).ToArray()).ToArray();
            return PairingDelta(distances, delta);
        }

        // The smallest limit that admits disjoint pairs for every row.
        private static double PairingDelta(double[][] distances, double minimum)
        {
            var thresholds = distances.SelectMany(row => row).Where(d => d > minimum && !double.IsInfinity(d))
                .Append(minimum).Distinct().OrderBy(d => d).ToArray();
            int first = 0, last = thresholds.Length;
            while (first < last)
            {
                int mid = first + (last - first) / 2;
                double tolerance = thresholds[mid];
                if (HasCompleteMatching(distances.Length, (i, j) => distances[i][j] <= tolerance))
                    last = mid;
                else first = mid + 1;
            }
            return first < thresholds.Length ? thresholds[first] : double.PositiveInfinity;
        }

        private static double CurveDelta(double[][] a, double[][] b)
        {
            if (a == null || b == null || a.Length < 2 || a.Length != b.Length) return double.PositiveInfinity;
            double forward = 0, reverse = 0;
            for (int i = 0; i < a.Length; i++)
            {
                forward = Math.Max(forward, Delta(a[i], b[i], 2));
                reverse = Math.Max(reverse, Delta(a[i], b[b.Length - i - 1], 2));
            }
            return Math.Min(forward, reverse);
        }

        private static bool SameGeometry(double[][] a, double[][] b, double tolerance = SolidToleranceFeet) =>
            SameGeometry(a, b, tolerance, out _);

        private static bool SameGeometry(double[][] a, double[][] b, double tolerance, out long nodeVisits)
        {
            nodeVisits = 0;
            if (a == null) return true; // legacy/location-only signatures remain usable
            if (b == null || a.Length != b.Length) return false;
            if (Enumerable.Range(0, a.Length).All(i => Delta(a[i], b[i]) <= tolerance)) return true;
            if (a.Any(p => !IsPoint(p)) || b.Any(p => !IsPoint(p))) return false;

            double[][] sortedA = SortPoints(a), sortedB = SortPoints(b);
            if (Enumerable.Range(0, a.Length).All(i => Delta(sortedA[i], sortedB[i]) <= tolerance)) return true;
            return CopySampleMatching.HasCompleteMatching(sortedA, sortedB, tolerance, out nodeVisits);
        }

        private static bool IsPoint(double[] point) =>
            point != null && point.Length == 3 && point.All(x => !double.IsNaN(x) && !double.IsInfinity(x));

        private static double[][] SortPoints(double[][] points) =>
            points.OrderBy(p => p[0]).ThenBy(p => p[1]).ThenBy(p => p[2]).ToArray();

        private static bool SamePosition(double[] a, double[] b) => Delta(a, b) <= SolidToleranceFeet;

        public static void StampSampleDelta(JObject row, CopySignature a, CopySignature b, bool placementMatches)
        {
            double[][] left = a.GeometryPoints, right = b.GeometryPoints;
            if (left != null && right != null && left.Length != right.Length)
                row["sample_count_differs"] = true;
            row["sample_delta_mm"] = JValue.CreateNull();
            if (!placementMatches)
            {
                row["sample_delta_status"] = "skipped_placement_mismatch";
                return;
            }

            var measured = SampleDelta(left, right);
            row["sample_delta_status"] = measured.Status;
            if (measured.Status == "exact" && !double.IsInfinity(measured.Exact))
                row["sample_delta_mm"] = measured.Exact * 304.8;
            if (measured.Status == "bounded")
            {
                row["sample_delta_lower_bound_mm"] = measured.Lower * 304.8;
                row["sample_delta_upper_bound_mm"] = measured.Upper * 304.8;
            }
        }

        // Exact bottleneck for small sets. For larger sets each axis's sorted
        // distances give a lower bound; any specific pairing gives an upper bound.
        private static (string Status, double Exact, double Lower, double Upper) SampleDelta(double[][] a, double[][] b)
        {
            if (a == null || b == null)
                return ("unavailable", double.NaN, double.NaN, double.NaN);
            if (a.Length != b.Length)
                return ("count_differs", double.NaN, double.NaN, double.NaN);
            if (a.Length == 0 || a.Any(p => !IsPoint(p)) || b.Any(p => !IsPoint(p)))
                return ("unavailable", double.NaN, double.NaN, double.NaN);
            if (a.Length <= ExactSampleDeltaLimit)
                return ("exact", PairingDelta(a.Select(p => b.Select(q => Delta(p, q)).ToArray()).ToArray(), 0),
                    double.NaN, double.NaN);

            double lower = 0;
            for (int axis = 0; axis < 3; axis++)
            {
                int index = axis;
                lower = Math.Max(lower, a.Select(p => p[index]).OrderBy(x => x)
                    .Zip(b.Select(p => p[index]).OrderBy(x => x), (x, y) => Math.Abs(x - y)).Max());
            }
            double upper = SortPoints(a).Zip(SortPoints(b), (p, q) => Delta(p, q)).Max();
            return lower == upper ? ("exact", lower, double.NaN, double.NaN)
                : ("bounded", double.NaN, lower, upper);
        }

        public static double Delta(double[] a, double[] b, int axes = 3)
        {
            if (a == null || b == null || a.Length != 3 || b.Length != 3) return double.PositiveInfinity;
            double delta = 0;
            for (int axis = 0; axis < axes; axis++)
            {
                double diff = Math.Abs(a[axis] - b[axis]);
                if (double.IsNaN(diff) || double.IsInfinity(diff)) return double.PositiveInfinity;
                delta = Math.Max(delta, diff);
            }
            return delta;
        }
    }
