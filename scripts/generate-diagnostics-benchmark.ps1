#Requires -Version 5.1
<#
  THE BENCHMARK'S EVIDENCE, GENERATED.

  docs/MODEL-DIAGNOSTICS-WORLD-BENCHMARK.md is written by hand: it argues. This
  script writes the part that must not be argued - the source inventory and the
  claim-to-source table - from docs/evidence/model-diagnostics-sources.json, so
  that every sentence in the benchmark can be traced to a URL and a label, and
  so the eight sweeps can be REPEATED rather than believed.

  A benchmark that says "eight independent sweeps" without keeping the sources
  is asking to be taken on trust, which is the one thing this document exists to
  refuse other people.

  Usage:
    pwsh -File scripts/generate-diagnostics-benchmark.ps1
#>
[CmdletBinding()]
param([string]$Sources, [string]$Out)
Set-StrictMode -Version Latest
$ErrorActionPreference = 'Stop'

$repo = Split-Path -Parent $PSScriptRoot
if (-not $Sources) { $Sources = Join-Path $repo 'docs\evidence\model-diagnostics-sources.json' }
if (-not $Out) { $Out = Join-Path $repo 'docs\MODEL-DIAGNOSTICS-BENCHMARK-SOURCES.md' }
if (-not (Test-Path -LiteralPath $Sources)) { throw "sources not found: $Sources" }

$d = Get-Content -LiteralPath $Sources -Raw | ConvertFrom-Json
$sha = (Get-FileHash -LiteralPath $Sources -Algorithm SHA256).Hash.ToLowerInvariant()
$products = @($d.products)

$KINDLABEL = @{
    official_documentation = 'official documentation'
    source_code            = 'shipped source code'
    marketing              = 'marketing'
    third_party_review     = 'third-party review'
    own_measurement        = 'own measurement'
}

function Esc([string]$s) {
    if ($null -eq $s) { return '' }
    ($s -replace '\|', '\|') -replace '\r?\n', ' '
}

$dimNames = @{}
foreach ($p in $d.dimensions.PSObject.Properties) { $dimNames[[int]$p.Name] = [string]$p.Value }

$sb = New-Object System.Text.StringBuilder
function W([string]$line) { $null = $sb.AppendLine($line) }

W '# Native-Revit model diagnostics — the sources'
W ''
W '<!-- GENERATED by scripts/generate-diagnostics-benchmark.ps1 from'
W '     docs/evidence/model-diagnostics-sources.json. Do not edit by hand: edit the'
W '     JSON, or re-run the sweeps that produce it. -->'
W ''
W ('Generated ' + (Get-Date).ToUniversalTime().ToString('yyyy-MM-dd') +
  ' from `docs/evidence/model-diagnostics-sources.json`, SHA-256 `' + $sha + '`.')
W ''
W 'This is the evidence behind [MODEL-DIAGNOSTICS-WORLD-BENCHMARK.md](MODEL-DIAGNOSTICS-WORLD-BENCHMARK.md).'
W 'That document argues; this one only cites. Every claim there should be findable here with a URL beside it.'
W ''
W '## How to read a label'
W ''
W '| Label | Means |'
W '|---|---|'
foreach ($k in @('MEASURED', 'DOCUMENTED', 'MARKETING', 'UNKNOWN')) {
    W ('| **' + $k + '** | ' + (Esc $d.labels.$k) + ' |')
}
W ''
W 'The label describes the **source type**, not how plausible the claim is. A feature bullet on a vendor''s own'
W 'front page is `MARKETING` however true it may be, because a promise is not a description of behaviour. An'
W '`UNKNOWN` is always accompanied by what was searched, and never means "the tool does not do this".'
W ''

# ---------------------------------------------------------------- the totals
$allSources = @($products | ForEach-Object { $_.sources })
$allClaims = @($products | ForEach-Object { $_.claims })
$allUnknowns = @($products | ForEach-Object { $_.unknowns })
$allContra = @($products | ForEach-Object { $_.contradictions })

W '## What this corpus is'
W ''
W '| | Count |'
W '|---|---:|'
W ('| Products swept | ' + $products.Count + ' |')
W ('| Distinct sources cited | ' + $allSources.Count + ' |')
W ('| Claims, each tied to at least one source | ' + $allClaims.Count + ' |')
W ('| Dimensions recorded as UNKNOWN, each with what was searched | ' + $allUnknowns.Count + ' |')
W ('| Contradictions between two sources, printed rather than resolved | ' + $allContra.Count + ' |')
W ''
W '### Sources by kind'
W ''
W '| Kind | Count |'
W '|---|---:|'
foreach ($kind in @('official_documentation', 'source_code', 'third_party_review', 'marketing', 'own_measurement')) {
    $n = @($allSources | Where-Object { $_.kind -eq $kind }).Count
    if ($n -eq 0) { continue }
    W ('| ' + $KINDLABEL[$kind] + ' | ' + $n + ' |')
}
W ''
W '### Claims by label'
W ''
W '| Label | Count |'
W '|---|---:|'
foreach ($lbl in @('MEASURED', 'DOCUMENTED', 'MARKETING', 'UNKNOWN')) {
    $n = @($allClaims | Where-Object { $_.label -eq $lbl }).Count
    W ('| ' + $lbl + ' | ' + $n + ' |')
}
W ''

# THE MEASURED ROWS, IN FULL. There are few enough to print, and the whole
# argument of the benchmark turns on how few and where they come from.
$measured = @()
foreach ($p in $products) {
    foreach ($c in @($p.claims | Where-Object { $_.label -eq 'MEASURED' })) {
        $measured += [pscustomobject]@{ Product = $p.product; Claim = $c; Sources = $p.sources }
    }
}
W '### Every MEASURED claim in the corpus'
W ''
if ($measured.Count -eq 0) {
    W 'There are none. Not one product in this set has a published, reproducible measurement behind any dimension.'
}
else {
    W ('There are ' + $measured.Count + '. They are printed in full because the benchmark''s central finding is')
    W 'about how few there are and where they come from — a reader should be able to check that in one screen.'
    W ''
    W '| Product | Dim | Claim | Source |'
    W '|---|---:|---|---|'
    foreach ($m in $measured) {
        $srcs = @()
        foreach ($id in @($m.Claim.source_ids)) {
            $s = @($m.Sources | Where-Object { $_.id -eq $id })
            if ($s.Count -gt 0) { $srcs += ('[' + (Esc $s[0].title) + '](' + $s[0].url + ')') }
        }
        W ('| ' + (Esc $m.Product) + ' | ' + $m.Claim.dimension + ' | ' + (Esc $m.Claim.claim) + ' | ' +
           ($srcs -join '<br>') + ' |')
    }
}
W ''
W '---'
W ''

# ------------------------------------------------------------- per product
foreach ($p in $products) {
    W ('## ' + $p.product)
    W ''
    W ('**Vendor:** ' + (Esc $p.vendor) + '  ')
    $ver = if ($p.PSObject.Properties.Name -contains 'product_version' -and $p.product_version) {
        Esc $p.product_version } else { 'not established by any source read' }
    W ('**Product version the sources describe:** ' + $ver)
    W ''

    W '### Sources'
    W ''
    W '| id | Kind | Title | Publisher | Dated | URL |'
    W '|---|---|---|---|---|---|'
    foreach ($s in @($p.sources)) {
        $dated = if ($s.PSObject.Properties.Name -contains 'dated' -and $s.dated) { Esc $s.dated } else { '—' }
        $pub = if ($s.PSObject.Properties.Name -contains 'publisher' -and $s.publisher) { Esc $s.publisher } else { '—' }
        W ('| `' + $s.id + '` | ' + $KINDLABEL[[string]$s.kind] + ' | ' + (Esc $s.title) + ' | ' + $pub +
           ' | ' + $dated + ' | <' + $s.url + '> |')
    }
    W ''
    $noted = @($p.sources | Where-Object {
        $_.PSObject.Properties.Name -contains 'note' -and $_.note -and $_.note.Length -gt 0 })
    if ($noted.Count -gt 0) {
        W '<details><summary>What each source does and does not carry</summary>'
        W ''
        foreach ($s in $noted) { W ('- **`' + $s.id + '`** — ' + (Esc $s.note)) }
        W ''
        W '</details>'
        W ''
    }

    W '### Claims, and what carries them'
    W ''
    W '| Dim | Dimension | Claim | Sources | Label |'
    W '|---:|---|---|---|---|'
    foreach ($c in @($p.claims | Sort-Object { [int]$_.dimension })) {
        $ids = @($c.source_ids | ForEach-Object { '`' + $_ + '`' })
        $dn = if ($dimNames.ContainsKey([int]$c.dimension)) { $dimNames[[int]$c.dimension] } else { '' }
        W ('| ' + $c.dimension + ' | ' + $dn + ' | ' + (Esc $c.claim) + ' | ' + ($ids -join ' ') +
           ' | ' + $c.label + ' |')
    }
    W ''

    $unk = @($p.unknowns)
    if ($unk.Count -gt 0) {
        W '### UNKNOWN, and what was searched'
        W ''
        W 'Each row is an absence of evidence, recorded as such. None of them says the product cannot do the thing.'
        W ''
        W '| Dim | Dimension | What was searched, and not found |'
        W '|---:|---|---|'
        foreach ($u in ($unk | Sort-Object { [int]$_.dimension })) {
            $dn = if ($dimNames.ContainsKey([int]$u.dimension)) { $dimNames[[int]$u.dimension] } else { '' }
            W ('| ' + $u.dimension + ' | ' + $dn + ' | ' + (Esc $u.why) + ' |')
        }
        W ''
    }

    $con = @($p.contradictions)
    if ($con.Count -gt 0) {
        W '### Contradictions'
        W ''
        W 'Printed, not resolved. Deciding between two vendor statements would be inventing a fact.'
        W ''
        foreach ($c in $con) { W ('- ' + (Esc $c)) }
        W ''
    }
    W '---'
    W ''
}

Set-Content -LiteralPath $Out -Value $sb.ToString() -Encoding UTF8

Write-Host ("[benchmark-sources] {0} products, {1} sources, {2} claims, {3} unknowns, {4} contradictions" -f
    $products.Count, $allSources.Count, $allClaims.Count, $allUnknowns.Count, $allContra.Count)
Write-Host ("[benchmark-sources] written to " + $Out)
